//Function
//Three Types Of Functions
// 1 . Normal function
// 2 . Anonamous Function
// 3 . Arrow Function

//NORMAL FUNCTION

//With return type and parameter
function sum(a,b){
    return a + b;
}
console.log(sum(10,20));

//Without return type and with parameter
function sum(a,b){
    console.log(a+b);
}
sum(10,20);

//Arrow Function
let sum=(a,b)=>{
    console.log(a+b);
}
sum(10,20)

